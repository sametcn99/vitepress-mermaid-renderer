/**
 * Post-build script to bundle TypeScript declarations into a single file.
 *
 * vite-plugin-dts generates individual .d.ts files under dist/src/ +
 * some stray files at dist root level. This script merges everything
 * into a single dist/index.d.ts and removes the extras (~72KB savings).
 */

import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  unlinkSync,
  rmdirSync,
} from 'fs';
import { join, relative } from 'path';
import { fileURLToPath } from 'url';

const distDir = join(fileURLToPath(new URL('..', import.meta.url)), 'dist');
const srcDir = join(distDir, 'src');

function collectDts(base, dir) {
  const map = new Map();
  if (!existsSync(dir)) return map;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      for (const [k, v] of collectDts(base, full)) map.set(k, v);
    } else if (entry.name.endsWith('.d.ts')) {
      const key = relative(base, full)
        .replace(/\\/g, '/')
        .replace(/\.d\.ts$/, '');
      map.set(key, readFileSync(full, 'utf-8'));
    }
  }
  return map;
}

function bundle(srcDecls) {
  const lines = [
    '// Type definitions for vitepress-mermaid-renderer',
    '// Generated by bundle-types.mjs\n',
  ];

  for (const [mod, content] of srcDecls) {
    const body = content
      .split('\n')
      .filter((l) => {
        const t = l.trim();
        // Drop triple-slash references
        if (t.startsWith('/// <reference')) return false;
        // Drop internal relative imports (will be inlined)
        if (
          (t.startsWith('import ') || t.startsWith('import type ')) &&
          /['"]\.\//.test(t)
        )
          return false;
        // Drop internal re-exports
        if (
          (t.startsWith('export * from ') ||
            (t.startsWith('export type {') && t.includes('from'))) &&
          /['"]\.\//.test(t)
        )
          return false;
        return true;
      })
      .join('\n');

    lines.push(`// ── ${mod} ──`);
    lines.push(body);
    lines.push('');
  }

  // Deduplicate by writing unique lines
  const seen = new Set();
  const deduped = lines
    .flatMap((l) => l.split('\n'))
    .filter((l) => {
      const t = l.trim();
      // Remove duplicate `export {}` or `export {};`
      if (/^export \{\};?$/.test(t)) {
        if (seen.has('export {}')) return false;
        seen.add('export {}');
      }
      return true;
    })
    .join('\n');

  // Simplify Vue SFC internal verbose types (__VLS_export -> DefineComponent)
  const cleaned = deduped.replace(
    /declare const __VLS_export: import\('vue'\)\.DefineComponent<__VLS_Props,[\s\S]*?declare const _default: typeof __VLS_export;\s*export default _default;/g,
    "declare const _default: import('vue').DefineComponent<__VLS_Props, {}, any>;\nexport default _default;",
  );

  const outPath = join(distDir, 'index.d.ts');
  writeFileSync(outPath, cleaned, 'utf-8');
  console.log(
    `✓ dist/index.d.ts bundled (${(Buffer.byteLength(cleaned, 'utf-8') / 1024).toFixed(1)} KB)`,
  );
}

function removeTree(dir) {
  if (!existsSync(dir)) return 0;
  let c = 0;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const f = join(dir, e.name);
    if (e.isDirectory()) c += removeTree(f);
    else {
      unlinkSync(f);
      c++;
    }
  }
  rmdirSync(dir);
  return c;
}

// ── Main ──
const srcDecls = collectDts(srcDir, srcDir);
if (!srcDecls.size) {
  console.log('ℹ No declarations found in dist/src/');
  process.exit(0);
}

console.log(`✓ Collected ${srcDecls.size} decl files from dist/src/`);
bundle(srcDecls);

let removed = removeTree(srcDir);
for (const f of ['playwright.config.d.ts', 'vitest.setup.d.ts']) {
  const p = join(distDir, f);
  if (existsSync(p)) {
    unlinkSync(p);
    removed++;
    console.log(`✓ Removed ${f}`);
  }
}
console.log(`✓ Removed ${removed} extra files`);
